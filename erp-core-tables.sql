create table if not exists public.erp_settings(
  id bigint generated by default as identity primary key,
  setting_key text unique not null,
  setting_value text,
  setting_group text default 'general',
  updated_at timestamptz default now()
);

create table if not exists public.erp_number_sequences(
  id bigint generated by default as identity primary key,
  sequence_type text unique not null,
  prefix text not null,
  last_number bigint default 0,
  padding integer default 5,
  suffix text default '',
  active boolean default true,
  updated_at timestamptz default now()
);

create table if not exists public.audit_log(
  id bigint generated by default as identity primary key,
  action text not null,
  module text,
  record_type text,
  record_id text,
  old_data jsonb,
  new_data jsonb,
  user_name text,
  created_at timestamptz default now()
);

