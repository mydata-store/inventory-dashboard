create or replace function public.next_erp_number(p_type text)
returns text
language plpgsql
security definer
as $$
declare
  seq public.erp_number_sequences%rowtype;
  result text;
begin
  select * into seq from public.erp_number_sequences
  where sequence_type=upper(p_type) and active=true
  for update;

  if not found then
    raise exception 'Number sequence not found for %',p_type;
  end if;

  update public.erp_number_sequences
  set last_number=last_number+1,updated_at=now()
  where id=seq.id
  returning * into seq;

  result:=seq.prefix||lpad(seq.last_number::text,seq.padding,'0')||coalesce(seq.suffix,'');
  return result;
end $$;

alter table public.erp_settings enable row level security;
alter table public.erp_number_sequences enable row level security;
alter table public.audit_log enable row level security;

drop policy if exists "Public all erp_settings" on public.erp_settings;
create policy "Public all erp_settings" on public.erp_settings for all using(true) with check(true);

drop policy if exists "Public all erp_number_sequences" on public.erp_number_sequences;
create policy "Public all erp_number_sequences" on public.erp_number_sequences for all using(true) with check(true);

drop policy if exists "Public all audit_log" on public.audit_log;
create policy "Public all audit_log" on public.audit_log for all using(true) with check(true);

grant execute on function public.next_erp_number(text) to anon,authenticated;
